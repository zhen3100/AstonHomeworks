package com.evgeniy.aston.service;

import com.evgeniy.aston.entity.User;
import java.util.List;
import java.util.Optional;

/**
 * Сервисный интерфейс для управления сущностями User
 * <p>Этот интерфейс определяет слой бизнес-логики для управления пользователями, предоставляя методы
 * для создания, получения, обновления, удаления пользователей
 */
public interface UserService {

    /**
     * Создает нового пользователя с указанными данными
     *
     * @param name полное имя пользователя; не должно быть null или пустым, должно содержать только
     *                  допустимые символы
     * @param email адрес электронной почты пользователя; не должен быть null или пустым, должен быть
     *                  в правильном формате email и должен быть уникальным среди всех пользователей
     * @param age возраст пользователя; не должен быть null и должен быть в диапазоне от 0 до 150 включительно
     * @return созданная сущность User;  никогда не null
     * @throws IllegalArgumentException если любой параметр невалиден
     */
    User createUser(String name, String email, Integer age);

    /**
     * Получает пользователя по его уникальному идентификатору.
     *
     * @param id уникальный идентификатор пользователя для получения; не должен быть null
     * @return Optional содержащий найденного User если существует, или пустой Optional если пользователь
     * @throws IllegalArgumentException если id равен null
     */
    Optional<User> getUserById(Long id);

    /**
     * Получает пользователя по его адресу электронной почты.
     *
     * @param email адрес электронной почты для поиска; не должен быть null или пустым, должен быть
     *              в правильном формате email
     * @return Optional содержащий найденного User если существует, или пустой Optional если пользователь
     * @throws IllegalArgumentException если email равен null, пустой или в невалидном формате
     */
    Optional<User> getUserByEmail(String email);

    /**
     * Получает всех пользователей из системы.
     *
     * @return List содержащий все сущности User; никогда не null, но может быть пустым
     */
    List<User> getAllUsers();

    /**
     * Обновляет информацию существующего пользователя.
     *
     * @param id id уникальный идентификатор пользователя для обновления; не должен быть null и должен
     *             соответствовать существующему пользователю
     * @param name полное имя пользователя; не должно быть null или пустым, должно содержать только
     *             допустимые символы
     * @param email адрес электронной почты пользователя; не должен быть null или пустым, должен быть
     *              в правильном формате email и должен быть уникальным среди всех пользователей
     * @param age возраст пользователя; не должен быть null и должен быть в диапазоне от 0 до 150 включительно
     * @return обновленная сущность User с измененными полями; никогда не null
     * @throws IllegalArgumentException если id равен null, пользователь не найден, любой параметр
     *              невалиден, или email уже используется другим пользователем
     */
    User updateUser(Long id, String name, String email, Integer age);

    /**
     * Удаляет пользователя по его уникальному идентификатору.
     * @param id уникальный идентификатор пользователя для удаления; не должен быть null
     *@throws IllegalArgumentException если id равен null
     */
    void deleteUserById(Long id);

    /**
     * Удаляет пользователя по его адресу электронной почты.
     * @param email адрес электронной почты пользователя для удаления; не должен быть null или пустым
     * @throws IllegalArgumentException если email равен null, пустой или в невалидном формате
     */
    void deleteUserByEmail(String email);
}
